// Package storage keeps resume PDFs. Handlers depend on the Storage interface
// so another backend (an object store, or a user's own cloud drive) can be
// added without touching routes.
package storage

import (
	"context"
	"errors"
	"fmt"
	"io"
	"io/fs"
	"os"
	"path"
	"regexp"

	"github.com/google/uuid"
)

// ErrNotExist is returned by Open when the object is missing.
var ErrNotExist = errors.New("storage: object does not exist")

type Storage interface {
	// Put stores r as a new PDF owned by userID and returns its key.
	Put(ctx context.Context, userID string, r io.Reader) (key string, err error)
	// Open returns the object's contents, or ErrNotExist.
	Open(ctx context.Context, key string) (io.ReadCloser, error)
	// Delete removes the object. Deleting a missing object is not an error.
	Delete(ctx context.Context, key string) error
}

// Keys look like "<userId>/<uuid>.pdf". Both parts are generated by the server
// (user IDs are UUIDs), never taken from user input; the pattern is checked
// anyway before any path is built.
var keyPattern = regexp.MustCompile(`^[0-9a-f-]{36}/[0-9a-f-]{36}\.pdf$`)

// Disk stores objects under dir/<userId>/<uuid>.pdf. All file access goes
// through an os.Root, so a key can never reach outside dir.
type Disk struct {
	root *os.Root
}

func NewDisk(dir string) (*Disk, error) {
	if err := os.MkdirAll(dir, 0o750); err != nil {
		return nil, fmt.Errorf("create storage directory: %w", err)
	}
	root, err := os.OpenRoot(dir)
	if err != nil {
		return nil, err
	}
	return &Disk{root: root}, nil
}

func (d *Disk) Close() error { return d.root.Close() }

func checkKey(key string) error {
	if !keyPattern.MatchString(key) {
		return fmt.Errorf("storage: invalid key %q", key)
	}
	return nil
}

// Put writes to a temporary file in the user's directory, then renames it into
// place, so a reader never sees a half-written PDF.
func (d *Disk) Put(_ context.Context, userID string, r io.Reader) (string, error) {
	if uuid.Validate(userID) != nil {
		return "", fmt.Errorf("storage: invalid user ID")
	}
	key := path.Join(userID, uuid.NewString()+".pdf")
	if err := checkKey(key); err != nil {
		return "", err
	}
	if err := d.root.MkdirAll(userID, 0o750); err != nil {
		return "", err
	}
	tmp := key + ".tmp"
	f, err := d.root.OpenFile(tmp, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0o640)
	if err != nil {
		return "", err
	}
	_, err = io.Copy(f, r)
	if cerr := f.Close(); err == nil {
		err = cerr
	}
	if err == nil {
		err = d.root.Rename(tmp, key)
	}
	if err != nil {
		_ = d.root.Remove(tmp)
		return "", err
	}
	return key, nil
}

func (d *Disk) Open(_ context.Context, key string) (io.ReadCloser, error) {
	if err := checkKey(key); err != nil {
		return nil, err
	}
	f, err := d.root.Open(key)
	if errors.Is(err, fs.ErrNotExist) {
		return nil, ErrNotExist
	}
	return f, err
}

func (d *Disk) Delete(_ context.Context, key string) error {
	if err := checkKey(key); err != nil {
		return err
	}
	err := d.root.Remove(key)
	if errors.Is(err, fs.ErrNotExist) {
		return nil
	}
	return err
}
